/* USER CODE BEGIN Header_sensorTask1 */
/**
* @brief Function implementing the sensorTask thread.
* @param argument: Not used
* @retval None
*/
/* USER CODE END Header_sensorTask1 */

void sensorTask1(void const * argument)
{
    /* USER CODE BEGIN sensorTask1 */

    uint8_t raw[16];
    uint8_t calib[16];

    for (;;)
    {
        /* ============================================
         * HTS221 - Temperature and Humidity
         * ============================================ */

        if (HAL_I2C_Mem_Read(&hi2c2, (0x5F << 1),
                             (0x30 | 0x80),
                             I2C_MEMADD_SIZE_8BIT,
                             calib, 16, 100) == HAL_OK &&
            HAL_I2C_Mem_Read(&hi2c2, (0x5F << 1),
                             (0x28 | 0x80),
                             I2C_MEMADD_SIZE_8BIT,
                             raw, 4, 100) == HAL_OK)
        {
            int16_t h0_out =
                (int16_t)((calib[7] << 8) | calib[6]);

            int16_t h1_out =
                (int16_t)((calib[11] << 8) | calib[10]);

            int16_t t0_out =
                (int16_t)((calib[13] << 8) | calib[12]);

            int16_t t1_out =
                (int16_t)((calib[15] << 8) | calib[14]);

            float h0 = calib[0] / 2.0f;
            float h1 = calib[1] / 2.0f;

            uint16_t t0_x8 =
                ((uint16_t)(calib[5] & 0x03) << 8) | calib[2];

            uint16_t t1_x8 =
                ((uint16_t)(calib[5] & 0x0C) << 6) | calib[3];

            float t0 = t0_x8 / 8.0f;
            float t1 = t1_x8 / 8.0f;

            int16_t h_raw =
                (int16_t)((raw[1] << 8) | raw[0]);

            int16_t t_raw =
                (int16_t)((raw[3] << 8) | raw[2]);

            if (h1_out != h0_out && t1_out != t0_out)
            {
                float humidity =
                    h0 + ((float)(h_raw - h0_out) *
                    (h1 - h0)) / (h1_out - h0_out);

                float temperature =
                    t0 + ((float)(t_raw - t0_out) *
                    (t1 - t0)) / (t1_out - t0_out);

                if (xSemaphoreTake(sensorMutex, portMAX_DELAY) == pdTRUE)
                {
                    sensorData.temperature = temperature;
                    sensorData.humidity = humidity;

                    xSemaphoreGive(sensorMutex);
                }
            }
        }

        /* ============================================
         * LIS3MDL - Magnetometer
         * ============================================ */

        if (HAL_I2C_Mem_Read(&hi2c2, (0x1E << 1),
                             (0x28 | 0x80),
                             I2C_MEMADD_SIZE_8BIT,
                             raw, 6, 100) == HAL_OK)
        {
            int16_t mag_x_raw =
                (int16_t)((raw[1] << 8) | raw[0]);

            int16_t mag_y_raw =
                (int16_t)((raw[3] << 8) | raw[2]);

            int16_t mag_z_raw =
                (int16_t)((raw[5] << 8) | raw[4]);

            float mag_x =
                (float)mag_x_raw * 1000.0f / 6842.0f;

            float mag_y =
                (float)mag_y_raw * 1000.0f / 6842.0f;

            float mag_z =
                (float)mag_z_raw * 1000.0f / 6842.0f;

            if (xSemaphoreTake(sensorMutex, portMAX_DELAY) == pdTRUE)
            {
                sensorData.mag_x = mag_x;
                sensorData.mag_y = mag_y;
                sensorData.mag_z = mag_z;

                xSemaphoreGive(sensorMutex);
            }
        }

        /* ============================================
         * LSM6DSL - Accelerometer and Gyroscope
         * ============================================ */

        if (HAL_I2C_Mem_Read(&hi2c2, (0x6A << 1),
                             0x22,
                             I2C_MEMADD_SIZE_8BIT,
                             raw, 12, 100) == HAL_OK)
        {
            /* Gyroscope raw data */

            int16_t gyro_x_raw =
                (int16_t)((raw[1] << 8) | raw[0]);

            int16_t gyro_y_raw =
                (int16_t)((raw[3] << 8) | raw[2]);

            int16_t gyro_z_raw =
                (int16_t)((raw[5] << 8) | raw[4]);

            /* Accelerometer raw data */

            int16_t acc_x_raw =
                (int16_t)((raw[7] << 8) | raw[6]);

            int16_t acc_y_raw =
                (int16_t)((raw[9] << 8) | raw[8]);

            int16_t acc_z_raw =
                (int16_t)((raw[11] << 8) | raw[10]);

            /* Convert gyroscope to degrees/second */

            float gyro_x =
                (float)gyro_x_raw * 0.00875f;

            float gyro_y =
                (float)gyro_y_raw * 0.00875f;

            float gyro_z =
                (float)gyro_z_raw * 0.00875f;

            /* Convert acceleration to g */

            float acc_x =
                (float)acc_x_raw * 0.000061f;

            float acc_y =
                (float)acc_y_raw * 0.000061f;

            float acc_z =
                (float)acc_z_raw * 0.000061f;

            if (xSemaphoreTake(sensorMutex, portMAX_DELAY) == pdTRUE)
            {
                sensorData.gyro_x = gyro_x;
                sensorData.gyro_y = gyro_y;
                sensorData.gyro_z = gyro_z;

                sensorData.acc_x = acc_x;
                sensorData.acc_y = acc_y;
                sensorData.acc_z = acc_z;

                xSemaphoreGive(sensorMutex);
            }
        }

        /* ============================================
         * LPS22HB - Atmospheric Pressure
         * ============================================ */

        if (HAL_I2C_Mem_Read(&hi2c2, (0x5D << 1),
                             (0x28 | 0x80),
                             I2C_MEMADD_SIZE_8BIT,
                             raw, 3, 100) == HAL_OK)
        {
            int32_t pressure_raw =
                ((int32_t)raw[2] << 16) |
                ((int32_t)raw[1] << 8) |
                raw[0];

            /* Sign-extend the 24-bit pressure reading */

            if (pressure_raw & 0x800000)
            {
                pressure_raw |= (int32_t)0xFF000000;
            }

            float pressure =
                (float)pressure_raw / 4096.0f;

            if (xSemaphoreTake(sensorMutex, portMAX_DELAY) == pdTRUE)
            {
                sensorData.pressure = pressure;

                xSemaphoreGive(sensorMutex);
            }
        }

        /* Essential: let other FreeRTOS tasks execute */
        osDelay(100);
    }

    /* USER CODE END sensorTask1 */
}

/* USER CODE BEGIN Header_uartTask1 */
/**
* @brief Function implementing the uartTask thread.
* @param argument: Not used
* @retval None
*/
/* USER CODE END Header_uartTask1 */

void uartTask1(void const * argument)
{
    /* USER CODE BEGIN uartTask1 */

    char msg[200];
    SensorData_t localData;

    for (;;)
    {
        /* ============================================
         * Copy shared sensor measurements safely
         * ============================================ */

        if (xSemaphoreTake(sensorMutex, portMAX_DELAY) == pdTRUE)
        {
            localData = sensorData;

            xSemaphoreGive(sensorMutex);
        }

        /* Read the currently selected sensor */
        uint8_t sensor = selected_sensor;

        /* ============================================
         * Format selected sensor measurements
         * ============================================ */

        switch (sensor)
        {
            case 0:
                /* HTS221 */
                snprintf(
                    msg,
                    sizeof(msg),
                    "[HTS221] Temp: %.2f C | Humidity: %.2f %%RH\r\n",
                    localData.temperature,
                    localData.humidity
                );
                break;

            case 1:
                /* LIS3MDL */
                snprintf(
                    msg,
                    sizeof(msg),
                    "[LIS3MDL] X: %.2f | Y: %.2f | Z: %.2f mG\r\n",
                    localData.mag_x,
                    localData.mag_y,
                    localData.mag_z
                );
                break;

            case 2:
                /* LSM6DSL */
                snprintf(
                    msg,
                    sizeof(msg),
                    "[LSM6DSL] ACC: %.3f %.3f %.3f g | "
                    "GYRO: %.2f %.2f %.2f dps\r\n",
                    localData.acc_x,
                    localData.acc_y,
                    localData.acc_z,
                    localData.gyro_x,
                    localData.gyro_y,
                    localData.gyro_z
                );
                break;

            case 3:
                /* LPS22HB */
                snprintf(
                    msg,
                    sizeof(msg),
                    "[LPS22HB] Pressure: %.2f hPa\r\n",
                    localData.pressure
                );
                break;

            default:
                snprintf(
                    msg,
                    sizeof(msg),
                    "[FreeRTOS] Invalid sensor selection\r\n"
                );
                break;
        }

        /* ============================================
         * UART transmission
         * ============================================ */

        HAL_UART_Transmit(
            &huart1,
            (uint8_t *)msg,
            strlen(msg),
            1000
        );

        /* Print once per second */
        osDelay(100);
    }

    /* USER CODE END uartTask1 */
}

