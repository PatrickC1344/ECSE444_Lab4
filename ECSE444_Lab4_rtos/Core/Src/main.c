{
    /* USER CODE BEGIN buttonTask1 */

    TickType_t lastButtonTick = 0;
    const TickType_t debounceTicks = pdMS_TO_TICKS(200);

    for (;;)
    {
        if (xSemaphoreTake(buttonSemaphore, portMAX_DELAY) == pdTRUE)
        {
            TickType_t currentTick = xTaskGetTickCount();

            if ((currentTick - lastButtonTick) >= debounceTicks)
            {
                selected_sensor = (selected_sensor + 1) % 4;

                lastButtonTick = currentTick;
            }
        }
    }

    /* USER CODE END buttonTask1 */
}

